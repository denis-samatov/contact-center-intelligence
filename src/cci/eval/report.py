"""Result manifests and the Markdown evaluation report (``results/REPORT.md``)."""

from __future__ import annotations

import json
import platform
import subprocess
import sys
from datetime import UTC, datetime
from importlib import metadata
from pathlib import Path

PKGS = ("sherpa-onnx", "scikit-learn", "numpy", "pymorphy3", "mlflow", "fastapi", "sqlalchemy", "httpx")


def manifest() -> dict:
    def ver(p):
        try:
            return metadata.version(p)
        except metadata.PackageNotFoundError:
            return None

    try:
        commit = subprocess.run(["git", "rev-parse", "HEAD"], capture_output=True, text=True, check=True).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        commit = None
    return {
        "created_utc": datetime.now(UTC).isoformat(timespec="seconds"),
        "python": sys.version.split()[0],
        "platform": platform.platform(),
        "packages": {p: ver(p) for p in PKGS},
        "git_commit": commit,
        "command": sys.argv,
    }


def _f(v, d=3):
    if v is None:
        return "-"
    if isinstance(v, float):
        return f"{v:.{d}f}"
    return str(v)


def _ci(v):
    return f"[{v[0]:.3f}, {v[1]:.3f}]" if v else "-"


def _t(headers, rows):
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    out += ["| " + " | ".join(_f(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def build_report(results: Path) -> Path:
    def load(name):
        p = results / f"{name}.json"
        return json.loads(p.read_text(encoding="utf-8")) if p.exists() else None

    md = [
        "# Contact Center Intelligence: evaluation report",
        "",
        "All data is **synthetic** (generated dialogues rendered with Piper TTS voices). Numbers validate the",
        "pipeline and compare methods under identical conditions; they are **not** estimates of accuracy on real",
        "customer calls. Generated by `cci report` from `results/*.json`.",
        "",
    ]
    asr = [(n, load(n)) for n in ("asr_test_clean", "asr_test_telephony", "asr_test_noisy")]
    if any(r for _, r in asr):
        md += [
            "## 1. ASR (Russian) - WER/CER on the test split",
            "",
            "WER uses numeric normalization on both sides (number words -> digits) so that Whisper's digits and the",
            "transducers' words are compared fairly; the un-normalized WER is shown too.",
            "",
        ]
        rows = []
        for _name, r in asr:
            if not r:
                continue
            for b, m in r["backends"].items():
                rows.append(
                    [
                        r["condition"],
                        b,
                        m["wer"],
                        _ci(m["wer_ci95"]),
                        m["cer"],
                        m["wer_without_number_normalization"],
                        m["rtf"],
                        r["calls"],
                    ]
                )
        md += [_t(["condition", "backend", "WER", "95% CI", "CER", "WER (raw)", "RTF (CPU)", "calls"], rows), ""]
        for _name, r in asr:
            if r and r.get("diarization"):
                d = r["diarization"]
                md += [
                    f"**Diarization ({r['condition']})**: DER {d['der_mean']:.3f} (missed {d['missed_mean']:.3f}, false alarm "
                    f"{d['false_alarm_mean']:.3f}, confusion {d['confusion_mean']:.3f}); operator/client role accuracy "
                    f"{d['role_accuracy_mean']:.3f}; calls with role accuracy < 0.9: {d['calls_with_role_accuracy_below_0.9']}"
                    f" of {d['calls']}.",
                    "",
                ]
    nlp = load("nlp")
    if nlp:
        md += [
            "## 2. Intent classification (test split, family-disjoint templates)",
            "",
            "Conditions: `reference` = gold transcript; `asr` = GigaAM-v2 + diarization on telephony audio; "
            "`paraphrase` = LLM-rewritten client turns (facts verified).",
            "",
        ]
        rows = [
            [
                k.split("/")[0],
                k.split("/")[1],
                v["accuracy"],
                _ci(v["accuracy_ci95"]),
                v["macro_f1"],
                _ci(v["macro_f1_ci95"]),
                v["seconds_per_call"],
            ]
            for k, v in nlp["intent"].items()
        ]
        md += [_t(["model", "condition", "accuracy", "95% CI", "macro-F1", "95% CI", "s/call"], rows), ""]
        md += [
            "## 3. Case extraction",
            "",
            "Micro precision/recall over (call, field) pairs of the gold intent's schema. Rules were written against",
            "the generator's dialogue grammar, so `rules/reference` is an upper bound by construction.",
            "",
        ]
        rows = [
            [
                k.split("/")[0],
                k.split("/")[1],
                v["fields"]["precision"],
                v["fields"]["recall"],
                v["fields"]["f1"],
                v["contradictions"]["precision"],
                v["contradictions"]["recall"],
                v["preferences"]["f1"],
                v["seconds_per_call"],
            ]
            for k, v in nlp["extraction"].items()
        ]
        md += [
            _t(
                [
                    "extractor",
                    "condition",
                    "field P",
                    "field R",
                    "field F1",
                    "contradiction P",
                    "contradiction R",
                    "preferences F1",
                    "s/call",
                ],
                rows,
            ),
            "",
        ]
        s = nlp["selective"]
        md += [
            "## 4. Automation vs selective prediction with human review",
            "",
            f"Condition `{s['condition']}`. Intent-probability threshold chosen on **dev** for <= "
            f"{s['target_error_on_dev']:.0%} case error: **{s['chosen_threshold']}**. A case is wrong if intent, queue or any "
            "required field is wrong.",
            "",
        ]
        rows = []
        for key, title in (
            ("test_automate_all", "automate everything"),
            ("test_rules_only", "review on missing/contradiction"),
            ("test_selective", "+ confidence threshold (selective)"),
        ):
            v = s[key]
            rows.append([title, v["automation_rate"], v["error_rate_on_automated"], v["errors_automated"], v["n"]])
        md += [_t(["policy", "automation rate", "error rate on automated", "errors", "calls"], rows), ""]
        if nlp.get("llm_usage"):
            u = nlp["llm_usage"]
            md += [
                f"LLM usage during NLP evaluation (local Qwen3-1.7B Q4_K_M, CPU): {u['calls']} calls, "
                f"{u['prompt_tokens']} prompt + {u['completion_tokens']} completion tokens, {u['seconds']:.0f} s, "
                f"{u['failures']} failures, {u['repairs']} schema repairs. Monetary cost: none measured (local CPU).",
                "",
            ]
    para = load("paraphrase_test")
    if para:
        md += [
            f"Paraphrase set: {para['accepted']} of {para['client_turns']} client turns rewritten "
            f"(acceptance {para['acceptance_rate']:.2f}); rejections: {para['rejection_reasons']}.",
            "",
        ]
    rag = load("rag")
    if rag:
        md += [
            "## 5. Knowledge-base answers: no retrieval vs grounded",
            "",
            f"{rag['questions']} questions over {rag['chunks']} chunks of a **fictional** rulebook.",
            "",
            _t(["retrieval", "recall"], [[k, v] for k, v in rag["retrieval_recall"].items()]),
            "",
        ]
        if "grounded_fact_recall" in rag:
            md += [
                _t(
                    ["metric", "closed-book", "grounded (RAG)"],
                    [
                        ["fact recall", rag["closed_book_fact_recall"], rag["grounded_fact_recall"]],
                        ["fully correct answers", rag["closed_book_fully_correct"], rag["grounded_fully_correct"]],
                    ],
                ),
                "",
                f"Grounding checks on RAG answers: verified grounded {rag['verified_grounded_rate']:.3f}; citation precision "
                f"{rag['citation_precision']:.3f}; fully correct among verified {rag['fully_correct_when_verified']:.3f}.",
                "",
            ]
    md += [
        "## Limits",
        "",
        "* Synthetic, TTS-rendered speech; operator and client voices differ in gender (easier diarization).",
        "* Test phrasings are family-disjoint from training, but written by the same author as the generator.",
        "* An early debugging run of the rule extractor looked at a sample of the original test seed; the reported",
        "  test split is generated with a fresh seed after all rules were frozen.",
        "* LLM numbers come from one local 1.7B model on CPU; larger models or GPUs were not evaluated.",
        "",
    ]
    path = results / "REPORT.md"
    path.write_text("\n".join(md) + "\n", encoding="utf-8")
    return path
